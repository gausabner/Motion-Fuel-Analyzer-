#!/usr/bin/env python3
"""
expected_values.py - computes, in SQL against the mart views, the numbers the Power BI cards must show.

Each query mirrors the DAX of the measure it checks (same filters, same date role, same denominators), so a
difference in Power BI Desktop points to a modelling error (relationship, date table, measure), not to data.
Output: 04_powerbi/expected_values.md, used by BUILD_GUIDE.md (expected KPI values and the RLS test matrix).

Usage: python expected_values.py   (DSN from GBHS_DSN, default local gbhs_health_dw)
"""
from __future__ import annotations

import os
from pathlib import Path

import psycopg

HERE = Path(__file__).resolve().parent
DSN = os.environ.get("GBHS_DSN", "postgresql://postgres:postgres@localhost:5432/gbhs_health_dw")

ED = "JOIN mart.v_dim_encounter_profile ep ON ep.encounter_profile_key = e.encounter_profile_key AND ep.department_code = 'ED'"


def one(conn, sql, params=()):
    return conn.execute(sql, params).fetchone()


def pct(v, d=1):
    return "" if v is None else f"{100 * float(v):.{d}f} %"


def num(v, d=0):
    return "" if v is None else f"{float(v):,.{d}f}"


def main():
    out = ["# Expected values for the Power BI checks", "",
           "Generated by `expected_values.py` from the mart views. Every query mirrors the DAX of the measure (same date role,",
           "filters and denominator). Data are deterministic (generator seed 20261028), so a rebuild reproduces these values.", ""]
    with psycopg.connect(DSN) as c:
        last = one(c, "SELECT max(arrival_date_key) FROM mart.v_fact_encounter")[0]
        last_epi = one(c, "SELECT max(epi_week_date_key) FROM mart.v_fact_surveillance")[0]
        out += [f"Last Data Date = {last} (attendances); last epi week starts {last_epi}.", ""]

        # ------------------------------------------------------------------ row counts
        views = ["v_dim_date", "v_dim_hour", "v_dim_region", "v_dim_facility", "v_dim_care_unit", "v_dim_patient", "v_dim_diagnosis",
                 "v_dim_condition", "v_dim_triage", "v_dim_encounter_profile", "v_dim_admission_profile", "v_dim_age_band", "v_dim_shift",
                 "v_fact_encounter", "v_fact_admission", "v_fact_ward_census", "v_fact_staff_roster", "v_fact_surveillance",
                 "v_fact_idsr_report", "v_fact_population", "v_fact_catchment_population", "v_fact_weather", "analytics_malaria_forecast",
                 "analytics_outbreak_alerts", "analytics_readmission_deciles", "analytics_readmission_drivers", "analytics_ed_drivers",
                 "v_dq_summary", "v_recon_latest", "v_sec_user_facility"]
        import model_spec as S
        names = {t["view"]: t["name"] for t in S.TABLES}
        out += ["## Row counts after refresh", "", "| Table | Source view | Rows |", "|---|---|---:|"]
        for v in views:
            out.append(f"| {names[v]} | mart.{v} | {one(c, f'SELECT count(*) FROM mart.{v}')[0]:,} |")
        out += ["| Metric Selector (calculated) | field parameter | 9 |", "| _Measures (calculated) | ROW() | 1 |", ""]

        # ------------------------------------------------------------------ executive cards per calendar year
        out += ["## Executive Overview cards by calendar year (slicer Calendar Year)", "",
                "| Card (measure) | 2025 | 2026 (to Last Data Date) | All years |", "|---|---:|---:|---:|"]

        def ed_count(d0, d1):
            return one(c, f"SELECT count(*) FROM mart.v_fact_encounter e {ED} WHERE e.arrival_date_key BETWEEN %s AND %s", (d0, d1))[0]

        cur25, py25 = ed_count(20250101, 20251231), ed_count(20240101, 20241231)
        cutoff_py = last - 10000                                          # EDATE(Last Data Date, -12) as a date key
        cur26, py26 = ed_count(20260101, 20261231), ed_count(20250101, min(20251231, cutoff_py))
        all_ed = ed_count(0, 99999999)
        # with no year selected TOTALYTD is evaluated at the last date of the calendar, i.e. the current (latest) year
        out.append(f"| ED Attendances YTD | {cur25:,} | {cur26:,} | {cur26:,} (latest year) |")
        out.append(f"| ED Attendances YTD YoY % | {pct(cur25 / py25 - 1)} (PY {py25:,}) | {pct(cur26 / py26 - 1)} (PY to {cutoff_py}: {py26:,}) "
                   f"| {pct(cur26 / py26 - 1)} |")

        def by_year(sql_tpl):
            r = []
            for d0, d1 in ((20250101, 20251231), (20260101, 20261231), (0, 99999999)):
                r.append(one(c, sql_tpl, (d0, d1))[0])
            return r
        swt = by_year("SELECT sum(seen_within_target)::numeric / count(seen_within_target) FROM mart.v_fact_encounter WHERE arrival_date_key BETWEEN %s AND %s")
        med = by_year(f"SELECT percentile_cont(0.5) WITHIN GROUP (ORDER BY door_to_doctor_min) FROM mart.v_fact_encounter e {ED} WHERE e.arrival_date_key BETWEEN %s AND %s")
        lwbs = by_year(f"SELECT avg(is_lwbs) FROM mart.v_fact_encounter e {ED} WHERE e.arrival_date_key BETWEEN %s AND %s")
        occ = by_year("SELECT sum(occupied_beds)::numeric / sum(beds_available) FROM mart.v_fact_ward_census WHERE census_date_key BETWEEN %s AND %s")
        readm = by_year("SELECT sum(readmitted_within_30d)::numeric / nullif(sum(readmission_eligible), 0) FROM mart.v_fact_admission WHERE discharge_date_key BETWEEN %s AND %s")
        alos = by_year("SELECT avg(los_days) FROM mart.v_fact_admission WHERE is_discharged = 1 AND discharge_date_key BETWEEN %s AND %s")
        out.append(f"| Seen Within Target % | {pct(swt[0])} | {pct(swt[1])} | {pct(swt[2])} |")
        out.append(f"| Median Door-to-Doctor (min) | {num(med[0])} | {num(med[1])} | {num(med[2])} |")
        out.append(f"| LWBS Rate % | {pct(lwbs[0])} | {pct(lwbs[1])} | {pct(lwbs[2])} |")
        out.append(f"| Bed Occupancy % | {pct(occ[0])} | {pct(occ[1])} | {pct(occ[2])} |")
        out.append(f"| Readmission Rate 30d % (by discharge date) | {pct(readm[0])} | {pct(readm[1])} | {pct(readm[2])} |")
        out.append(f"| ALOS (days) (by discharge date) | {num(alos[0], 2)} | {num(alos[1], 2)} | {num(alos[2], 2)} |")
        out.append(f"| ED Attendances (no slicer) | | | {all_ed:,} |")
        out.append("")

        # ------------------------------------------------------------------ surveillance cards per epi year
        out += ["## Disease Surveillance cards by epi year (slicer Epi Year)", "",
                "| Card (measure) | 2025 | 2026 (to last epi week) |", "|---|---:|---:|"]
        MAL = ("FROM mart.v_fact_surveillance s JOIN mart.v_dim_condition k ON k.condition_key = s.condition_key AND k.condition_code = 'MAL' "
               "JOIN mart.v_dim_date d ON d.date_key = s.epi_week_date_key")
        rows = {}
        for y in (2025, 2026):
            end = one(c, "SELECT least(max(full_date), (SELECT to_date(max(epi_week_date_key)::text, 'YYYYMMDD') + 6 FROM mart.v_fact_surveillance)) "
                         "FROM mart.v_dim_date WHERE epi_year = %s", (y,))[0]
            cases = one(c, f"SELECT sum(s.cases_total) {MAL} WHERE d.epi_year = %s AND d.full_date <= %s", (y, end))[0]
            cases_py = one(c, f"SELECT sum(s.cases_total) {MAL} WHERE d.epi_year = %s AND d.full_date <= %s::date - 364", (y - 1, end))[0]
            first = one(c, "SELECT to_date(min(epi_week_date_key)::text, 'YYYYMMDD') FROM mart.v_fact_surveillance")[0]
            days = one(c, "SELECT count(*) FROM mart.v_dim_date WHERE epi_year = %s AND full_date BETWEEN %s AND %s", (y, first, end))[0]
            pop = one(c, "SELECT sum(catchment_population) FROM mart.v_fact_catchment_population WHERE year_date_key = %s", (y * 10000 + 701,))[0]
            py_years = pop * days / 365
            tpos = one(c, "SELECT sum(tests_positive)::numeric / sum(tests_done) FROM mart.v_fact_surveillance s JOIN mart.v_dim_date d "
                          "ON d.date_key = s.epi_week_date_key WHERE d.epi_year = %s", (y,))[0]
            comp, tim = one(c, "SELECT avg(report_received), avg(report_on_time) FROM mart.v_fact_idsr_report r JOIN mart.v_dim_date d "
                               "ON d.date_key = r.epi_week_date_key WHERE d.epi_year = %s", (y,))
            rows[y] = dict(cases=cases, yoy=cases / cases_py - 1, py=cases_py, inc=1000 * cases / py_years, tpos=tpos, comp=comp, tim=tim,
                           days=days, pop=pop)
        r5, r6 = rows[2025], rows[2026]
        out.append(f"| Malaria Cases Epi-YTD | {r5['cases']:,} | {r6['cases']:,} |")
        out.append(f"| Malaria Cases Epi-YTD YoY % | {pct(r5['yoy'])} (PY {r5['py']:,}) | {pct(r6['yoy'])} (PY same weeks {r6['py']:,}) |")
        out.append(f"| Malaria Incidence per 1,000 PY | {r5['inc']:.1f} ({r5['days']} days x {r5['pop']:,}) | {r6['inc']:.1f} ({r6['days']} days x {r6['pop']:,}) |")
        out.append(f"| Malaria Test Positivity % | {pct(r5['tpos'])} | {pct(r6['tpos'])} |")
        out.append(f"| IDSR Completeness % | {pct(r5['comp'])} | {pct(r6['comp'])} |")
        out.append(f"| IDSR Timeliness % | {pct(r5['tim'])} | {pct(r6['tim'])} |")
        census = one(c, "SELECT sum(population) FROM mart.v_fact_population WHERE is_census_count")[0]
        out += ["", f"Census Population 2023 (no filters) = {census:,} (NSA 2023 census national total).",
                "The matrix 'Malaria incidence per 100 000 catchment population' equals `06_report/evidence/olap_pivot.md` cell by cell.", ""]

        # ------------------------------------------------------------------ advanced page
        wape = one(c, "SELECT sum(abs(actual - forecast)) / sum(abs(actual)) FROM mart.analytics_malaria_forecast WHERE kind = 'Back-test (1 week ahead)'")[0]
        cap = one(c, "SELECT sum(observed * spells) FILTER (WHERE decile >= 9) / sum(observed * spells) FROM mart.analytics_readmission_deciles")[0]
        ppv = one(c, "SELECT avg(is_injected_outbreak::int) FROM mart.analytics_outbreak_alerts")[0]
        rec = one(c, "SELECT avg((status = 'PASS')::int), count(*) FILTER (WHERE status = 'WARN') FROM mart.v_recon_latest")
        dq = one(c, "SELECT sum(issues), count(*) FILTER (WHERE issues > 0) FROM mart.v_dq_summary")
        out += ["## Advanced Analytics & DQ cards (no slicer selection)", "", "| Card (measure) | Expected |", "|---|---:|",
                f"| Backtest WAPE % (1 Week Ahead) | {pct(wape)} |", f"| Top-20% Risk Capture % | {pct(cap)} |",
                f"| Alerts in Known Outbreak Weeks % (all methods) | {pct(ppv)} |", f"| Reconciliation Pass % | {pct(rec[0])} ({rec[1]} WARN) |",
                f"| DQ Issues Logged | {dq[0]:,} ({dq[1]} rules triggered) |", "| Visible Facilities (Executive) | 10 |", ""]

        # ------------------------------------------------------------------ RLS matrix
        out += ["## Row-level security test matrix (Modeling > View as)", "",
                "| Other user (UPN) | Role | Visible Facilities | ED Attendances 2025 | Malaria cases, epi year 2025 |", "|---|---|---:|---:|---:|"]

        def fac_metrics(fac_keys):
            if not fac_keys:
                return "(blank)", "(blank)", "(blank)"
            ed25 = one(c, f"SELECT count(*) FROM mart.v_fact_encounter e {ED} JOIN mart.v_dim_care_unit cu ON cu.care_unit_key = e.care_unit_key "
                          "WHERE cu.facility_key = ANY(%s) AND e.arrival_date_key BETWEEN 20250101 AND 20251231", (fac_keys,))[0]
            mal = one(c, f"SELECT sum(s.cases_total) {MAL} WHERE s.facility_key = ANY(%s) AND d.epi_year = 2025", (fac_keys,))[0]
            return str(len(fac_keys)), f"{ed25:,}", f"{(mal or 0):,}"
        allf = [r[0] for r in c.execute("SELECT facility_key FROM mart.v_dim_facility WHERE facility_key > 0 ORDER BY 1")]
        out.append("| *(none)* | Executive (all facilities) | " + " | ".join(fac_metrics(allf)) + " |")
        users = [r[0] for r in c.execute("SELECT DISTINCT user_principal_name FROM mart.v_sec_user_facility WHERE user_principal_name LIKE 'fm.%%' ORDER BY 1")]
        for u in users:
            keys = [r[0] for r in c.execute("SELECT facility_key FROM mart.v_sec_user_facility WHERE user_principal_name = %s ORDER BY 1", (u,))]
            out.append(f"| {u} | Facility Manager (dynamic) | " + " | ".join(fac_metrics(keys)) + " |")
        out.append("| intruder@gbhs.example (not mapped) | Facility Manager (dynamic) | (blank) | (blank) | (blank) |")
        ne = [r[0] for r in c.execute("SELECT f.facility_key FROM mart.v_dim_facility f JOIN mart.v_dim_region r ON r.region_key = f.region_key "
                                      "WHERE r.zone = 'North-East' ORDER BY 1")]
        out.append("| *(none)* | North-East Zone (static) | " + " | ".join(fac_metrics(ne)) + " |")
        out.append("| *(none)* | Surveillance Partner (aggregate only) | 10 | error: table Attendance is not visible (OLS) | "
                   + fac_metrics(allf)[2] + " |")
        out.append("")
    (HERE / "expected_values.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    # the report (06_report) includes the tables section by section, so its numbers come from the same queries
    evidence = HERE.parent / "06_report" / "evidence"
    sections, name = {}, None
    for line in out:
        if line.startswith("## "):
            name = line[3:].split(" (")[0].lower().replace(" & ", "_").replace(" ", "_")
            sections[name] = []
        elif name and line.startswith("|"):
            sections[name].append(line)
    for name, lines in sections.items():
        (evidence / f"pbi_{name}.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(out))
    print("evidence:", ", ".join(f"pbi_{n}.md" for n in sections))


if __name__ == "__main__":
    main()
