"""
model_spec.py - declarative definition of the GBHS (Green Basket Health Services) Power BI semantic model.
Consumed by build_pbip.py, which emits TMSL (model.bim), validates it with Microsoft's Tabular Object
Model and serialises it to TMDL inside the Power BI Project (PBIP).

Design decisions (report section 3.4):
  * Storage mode: Import for every table. About 0.9 M fact rows fit easily in memory, all DAX time
    intelligence is available, there is no gateway round trip per visual, and the PostgreSQL warehouse is
    not hit by every slicer click. Attendance (the largest fact) has an incremental-refresh policy on its
    integer arrival date key (RangeStart/RangeEnd fold to SQL).
  * Relationships: many-to-one, single direction (dimension filters fact), one active path between any
    dimension and any fact. Admission has a second, inactive relationship to Date (discharge date,
    role-playing) activated with USERELATIONSHIP in the discharge-based measures.
  * Kept snowflakes: Care Unit -> Facility -> Region (ward-level facts roll up to facilities; surveillance,
    weather and catchment facts attach directly at facility grain) and Diagnosis -> Condition (encounters
    are coded in ICD-10, IDSR returns at condition grain; Condition is the conformed dimension).
  * Technical columns (keys) hidden; numeric fact columns hidden behind measures (discourageImplicitMeasures);
    measures in a dedicated _Measures table with display folders; sort-by columns for every label.
  * Security: dynamic RLS (Facility manager), static RLS (North-East zone) and object-level security
    (Surveillance partner: patient-level tables are invisible, not just empty).
"""

