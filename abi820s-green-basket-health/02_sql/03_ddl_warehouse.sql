-- =============================================================================
-- 03_ddl_warehouse.sql
-- Dimensional warehouse (Kimball bus architecture) for Green Basket Health Services.
--   Conformed dimensions : dim_date, dim_hour, dim_region, dim_facility, dim_care_unit (SCD2),
--                          dim_patient (SCD2), dim_diagnosis, dim_condition, dim_triage,
--                          dim_encounter_profile (junk), dim_admission_profile (junk),
--                          dim_age_band, dim_shift
--   Snowflaked hierarchies: dim_care_unit -> dim_facility -> dim_region
--                           dim_diagnosis -> dim_condition
--   Facts: fact_encounter (transaction), fact_admission (accumulating snapshot),
--          fact_ward_census_daily (periodic snapshot, semi-additive), fact_staff_roster
--          (periodic snapshot per shift), fact_surveillance_weekly (periodic snapshot),
--          fact_idsr_report (coverage / factless), fact_population (annual snapshot,
--          semi-additive, external), fact_weather_daily (periodic, external)
-- Special members: -1 = Unknown / not recorded, -2 = Not applicable (e.g. not yet discharged).
-- Every column carries a COMMENT "definition | Source: ..." that feeds the generated
-- data dictionary (03_analytics/build_data_dictionary.py).
-- =============================================================================

