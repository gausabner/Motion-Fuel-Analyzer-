-- =============================================================================
-- 03_ddl_warehouse.sql
-- Dimensional warehouse (Kimball bus architecture) for Green Basket cc.
--   Conformed dimensions : dim_date, dim_region, dim_crop_category, dim_crop,
--                          dim_product, dim_farm (SCD2), dim_customer (SCD2),
--                          dim_cost_category, dim_commodity
--   Snowflaked hierarchies: dim_product -> dim_crop -> dim_crop_category
--                           dim_farm    -> dim_region ; dim_customer -> dim_region
--   Facts: fact_sales (transaction), fact_harvest (transaction),
--          fact_production_cost (transaction), fact_crop_cycle (accumulating
--          snapshot), fact_inventory_monthly (periodic snapshot, semi-additive),
--          fact_weather_daily (periodic), fact_market_price_monthly (periodic,
--          non-additive), fact_crop_estimate (season benchmark, external)
-- Special members: -1 = Unknown, -2 = Not applicable (e.g. farm overhead cost).
-- Every column carries a COMMENT "definition | Source: ..." that feeds the
-- generated data dictionary (see 03_analytics/build_data_dictionary.py).
-- =============================================================================

