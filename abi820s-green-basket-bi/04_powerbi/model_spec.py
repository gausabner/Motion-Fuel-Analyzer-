"""
model_spec.py - declarative definition of the Green Basket Power BI semantic model.
Consumed by build_pbip.py, which emits TMSL (model.bim), validates it with Microsoft's Tabular Object
Model and serialises it to TMDL inside the Power BI Project (PBIP).

Design decisions (report section 3.4):
  * Storage mode: Import (all tables). 0.5 M rows fit easily in memory; full DAX time-intelligence;
    no gateway latency; incremental refresh on Sales via RangeStart/RangeEnd.
  * Relationships: many-to-one, single direction, dimension -> fact; inactive role-playing date
    relationships activated with USERELATIONSHIP.
  * Kept snowflakes: Region -> Farm and Crop Category -> Crop -> Product (facts attach at those grains).
  * Technical columns (keys, SCD hashes) hidden; numeric fact columns hidden behind measures
    (discourageImplicitMeasures); measures in a dedicated _Measures table with display folders.
"""

